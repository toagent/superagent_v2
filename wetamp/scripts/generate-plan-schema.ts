// Owner: wetamp/schemas/plan.schema.json. Never rewrite the runtime schema.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { format, resolveConfig } from 'prettier';

const target = fileURLToPath(new URL('../src/plan-types.generated.ts', import.meta.url));
const schema = JSON.parse(
  readFileSync(new URL('../schemas/plan.schema.json', import.meta.url), 'utf8')
);
const generated = await compile(schema, 'Plan', {
  ignoreMinAndMaxItems: true,
  unreachableDefinitions: false,
  bannerComment:
    '/* Generated by wetamp/scripts/generate-plan-schema.ts from wetamp/schemas/plan.schema.json. Do not edit. */',
});
const text = await format(generated, { ...(await resolveConfig(target)), filepath: target });
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    throw new Error('Plan types drift: run bun run --cwd wetamp generate:plan-types');
  }
} else {
  writeFileSync(target, text);
}
