// output.schema.json owns the enum; this script owns its embedded schemas and runtime type.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type outputSchema from '../schemas/output.schema.json';

const root = join(import.meta.dir, '..');
const path = join(root, 'schemas/output.schema.json');
const schema = JSON.parse(readFileSync(path, 'utf8')) as typeof outputSchema;
const before = JSON.stringify(schema);
const failure = schema.$defs.failure_class;
schema.$defs.reviewer.properties.findings.items.properties.failure_class = failure;
schema.$defs.accept.properties.failures.items.properties.failure_class = failure;
if (JSON.stringify(schema) !== before) writeFileSync(path, JSON.stringify(schema, null, 2) + '\n');
writeFileSync(
  join(root, 'templates/.archon/scripts/failure-class.ts'),
  '// Generated by wetamp/scripts/generate-failure-class.ts; edit output.schema.json instead.\n' +
    `export const FAILURE_CLASSES = ${JSON.stringify(failure.enum)} as const;\n` +
    'export type FailureClass = (typeof FAILURE_CLASSES)[number];\n' +
    'export const failureClass = (value: unknown): FailureClass =>\n' +
    "  FAILURE_CLASSES.find(c => c === value) ?? 'product';\n"
);
